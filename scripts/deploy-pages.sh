#!/usr/bin/env bash
# Deploy the student frontend to GitHub Pages and point it at the live API.
#
# The repo layout is:
#   main branch = the whole project (backend, scripts, docs) — what you clone
#   site branch = the student frontend only — what GitHub Pages serves
#
# Usage:
#   ./scripts/deploy-pages.sh <api-base-url> [owner/repo]
#
#   <api-base-url>  the public tunnel URL, no trailing slash,
#                   e.g. https://something-words.trycloudflare.com
#   [owner/repo]    GitHub repo (default: Shawky-Ahmad/ai-animal-lab).
#                   Created as a PUBLIC repo if it does not exist (gh CLI must
#                   be logged in; Pages serves the student site publicly).
#
# Re-run this script every time the tunnel URL changes (quick tunnels get a
# new URL on each start) — it commits and pushes the updated config.js.
set -euo pipefail

API_BASE="${1:?usage: deploy-pages.sh <api-base-url> [owner/repo]}"
API_BASE="${API_BASE%/}"   # no trailing slash
REPO="${2:-Shawky-Ahmad/ai-animal-lab}"
SITE_BRANCH="site"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/frontend/student"
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT

cp "$SRC"/*.html "$SRC"/*.css "$SRC"/*.js "$STAGE"/
cat > "$STAGE/config.js" <<EOF
// Auto-generated by scripts/deploy-pages.sh — API base for GitHub Pages.
// The student site is served by GitHub Pages; the API lives behind the tunnel.
window.ANIMAL_LAB_CONFIG = { API_BASE: "$API_BASE" };
EOF
: > "$STAGE/.nojekyll"

if ! gh repo view "$REPO" >/dev/null 2>&1; then
  echo "[pages] creating public repo $REPO ..."
  gh repo create "$REPO" --public
fi

cd "$STAGE"
git init -q -b main
git add -A
git -c user.name="animal-lab-deploy" -c user.email="noreply@local" \
  commit -q -m "deploy student site -> API $API_BASE"
git remote add origin "https://github.com/$REPO.git"
git push -q --force origin "main:$SITE_BRANCH"

# make sure GitHub Pages serves the site branch (switch it if it points elsewhere)
PAGES_BRANCH="$(gh api "repos/$REPO/pages" --jq '.source.branch' 2>/dev/null || true)"
if [ -z "$PAGES_BRANCH" ]; then
  echo "[pages] enabling GitHub Pages (branch: $SITE_BRANCH) ..."
  gh api -X POST "repos/$REPO/pages" \
    -f "source[branch]=$SITE_BRANCH" -f "source[path]=/" >/dev/null
elif [ "$PAGES_BRANCH" != "$SITE_BRANCH" ]; then
  echo "[pages] switching Pages source: $PAGES_BRANCH -> $SITE_BRANCH ..."
  gh api -X PUT "repos/$REPO/pages" \
    -f "source[branch]=$SITE_BRANCH" -f "source[path]=/" >/dev/null
fi

echo
echo "Deployed. Pages URL: https://$(echo "$REPO" | cut -d/ -f1).github.io/$(echo "$REPO" | cut -d/ -f2)/"
echo "First build takes ~1 minute; check: gh run list -R $REPO --workflow pages"
